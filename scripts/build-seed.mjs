#!/usr/bin/env node
/**
 * Seed builder: turns packages/content/data/{stories,timings}.json into
 *   - apps/mobile/src/content/assets.generated.ts  (static require() map for Metro bundling)
 *   - supabase/seed.sql                              (idempotent SQL seed for the optional backend)
 * Run: npm run seed:build   (re-run after editing content or regenerating narration)
 */
import { mkdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const stories = JSON.parse(readFileSync(join(root, 'packages/content/data/stories.json'), 'utf8'));
const timings = JSON.parse(readFileSync(join(root, 'packages/content/data/timings.json'), 'utf8'));

// ---------- mobile asset map ----------
const lines = [
  '// AUTO-GENERATED by scripts/build-seed.mjs — do not edit by hand.',
  '/* eslint-disable */',
  'export const storyImages: Record<string, number> = {',
];
for (const s of stories) for (const p of s.pages) lines.push(`  '${p.image}': require('../../assets/stories/${p.image}'),`);
lines.push('};', '', 'export const storyAudio: Record<string, number> = {');
for (const s of stories) for (const p of s.pages) lines.push(`  '${p.audio}': require('../../assets/stories/${p.audio}'),`);
lines.push(
  '};',
  '',
  '/** Bytes of bundled media per story (images + narration), for the downloads manager. */',
  'export const storyBytes: Record<string, number> = {',
);
for (const s of stories) {
  const bytes = s.pages.reduce(
    (n, p) => n + statSync(join(root, 'apps/mobile/assets/stories', p.image)).size + statSync(join(root, 'apps/mobile/assets/stories', p.audio)).size,
    0,
  );
  lines.push(`  '${s.id}': ${bytes},`);
}
lines.push('};', '');
const mobileOut = join(root, 'apps/mobile/src/content/assets.generated.ts');
mkdirSync(dirname(mobileOut), { recursive: true });
writeFileSync(mobileOut, lines.join('\n'));

// ---------- supabase seed ----------
const q = (v) => (v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => `array[${a.map(q).join(',')}]::text[]`;
const licenses = new Map();
for (const s of stories) {
  const key = `${s.license.kind}|${s.license.name}|${s.license.holder}|${s.license.notes}`;
  if (!licenses.has(key)) licenses.set(key, { ...s.license, id: `lic-${s.id}` });
  s._lic = licenses.get(key).id;
}
const sql = ['-- AUTO-GENERATED by scripts/build-seed.mjs from packages/content/data. Idempotent.', 'begin;', ''];
for (const l of licenses.values()) {
  sql.push(
    `insert into public.content_licenses (id, kind, name, holder, notes, url) values (${q(l.id)}, ${q(l.kind)}, ${q(l.name)}, ${q(l.holder)}, ${q(l.notes)}, ${q(l.url ?? null)}) on conflict (id) do update set kind = excluded.kind, name = excluded.name, holder = excluded.holder, notes = excluded.notes, url = excluded.url;`,
  );
}
sql.push('');
for (const s of stories) {
  sql.push(
    `insert into public.stories (id, title, origin, source, license_id, age_band, minutes, tags, moral, synopsis, characters, language, status, illustration_credit, illustration_kind, narration_credit, narration_voice, narration_kind, published_at) values (${[
      s.id,
      s.title,
      s.origin,
      s.source,
      s._lic,
      s.ageBand,
    ]
      .map(q)
      .join(', ')}, ${s.minutes}, ${arr(s.tags)}, ${[s.moral, s.synopsis, s.characters, s.language].map(q).join(', ')}, 'draft', ${[
      s.illustration.credit,
      s.illustration.kind,
      s.narration.credit,
      s.narration.voice,
      s.narration.kind,
    ]
      .map(q)
      .join(', ')}, null) on conflict (id) do update set title = excluded.title, synopsis = excluded.synopsis, moral = excluded.moral, tags = excluded.tags;`,
  );
  sql.push(
    `insert into public.rights_checklist (story_id, source_verified, license_verified, illustrations_cleared, narration_cleared, no_third_party_trademarks, notes) values (${q(s.id)}, true, true, true, true, true, 'Seed content: verified at import') on conflict (story_id) do nothing;`,
  );
  for (const p of s.pages) {
    const n = p.index;
    sql.push(
      `insert into public.assets (id, story_id, kind, bucket, path, mime_type, credit) values (${q(`${s.id}-${n}-img`)}, ${q(s.id)}, 'illustration', 'illustrations', ${q(`${s.id}/${n}.webp`)}, 'image/webp', ${q(s.illustration.credit)}) on conflict (id) do nothing;`,
      `insert into public.assets (id, story_id, kind, bucket, path, mime_type, credit) values (${q(`${s.id}-${n}-aud`)}, ${q(s.id)}, 'narration', 'narration', ${q(`${s.id}/${n}.mp3`)}, 'audio/mpeg', ${q(s.narration.credit)}) on conflict (id) do nothing;`,
      `insert into public.story_pages (story_id, page_index, text, scene_description, image_asset_id, audio_asset_id, audio_duration_sec, word_timings) values (${q(s.id)}, ${n}, ${q(p.text)}, ${q(p.sceneDescription)}, ${q(`${s.id}-${n}-img`)}, ${q(`${s.id}-${n}-aud`)}, ${p.audioDurationSec}, ${q(JSON.stringify(timings[p.timingKey] ?? []))}::jsonb) on conflict (story_id, page_index) do update set text = excluded.text, word_timings = excluded.word_timings, audio_duration_sec = excluded.audio_duration_sec;`,
    );
  }
  // Publishing goes through the rights gate trigger, exactly like the studio workflow.
  sql.push(`update public.stories set status = 'published', published_at = now() where id = ${q(s.id)} and status <> 'published';`, '');
}
sql.push('commit;', '');
writeFileSync(join(root, 'supabase/seed.sql'), sql.join('\n'));
console.log(`✔ Wrote assets map (${stories.reduce((n, s) => n + s.pages.length, 0)} pages) and supabase/seed.sql (${stories.length} stories).`);
